import Link from "next/link";
import { InsightCard } from "@/components/teacher/InsightCard";
import { StudentTable } from "@/components/teacher/StudentTable";
import { Badge, Card, EmptyState, Notice, PageHeader, SectionTitle, Stat } from "@/components/ui/primitives";
import { Heatmap } from "@/components/ui/Charts";
import { requireRole } from "@/lib/auth";
import { pct } from "@/lib/format";
import { getClassAnalytics, getTeacherClassroom, listInsights, refreshTeacherInsights } from "@/services/teacher";

export const metadata = { title: "Class overview" };

export default async function TeacherPage() {
  const session = await requireRole(["teacher"]);
  const classroom = await getTeacherClassroom(session.id);
  if (!classroom) return <EmptyState title="No classroom assigned" body="Ask an administrator to assign a classroom to your account, then your class learner models will appear here." />;

  const analysis = await getClassAnalytics(classroom.id);
  if (analysis.studentCount === 0) return <EmptyState title="No students have joined yet" body={`Share the classroom code ${classroom.joinCode} so students can join during onboarding.`} />;
  await refreshTeacherInsights(classroom.id, analysis);
  const insights = await listInsights(classroom.id);
  const attentionIds = new Set(analysis.attention.map((s) => s.id));
  const topMisconception = analysis.misconceptionStats[0];

  return (
    <>
      <PageHeader eyebrow={`Class overview · code ${classroom.joinCode}`} title={classroom.name} description="Aggregated from every student's living learner model." />
      <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-4">
        <Stat label="Students" value={analysis.studentCount} />
        <Stat label="Average mastery" value={pct(analysis.classAverage)} tone="indigo" />
        <Stat label="Students needing attention" value={analysis.attention.length} tone="rose" sub="low mastery, inactive or many misconceptions" />
        <Stat label="Concepts with largest gaps" value={analysis.hardest.length} sub={analysis.hardest.slice(0, 2).map((c) => c.name).join(", ")} />
      </div>

      {topMisconception && (
        <Card className="mt-6 border-rose-200 bg-gradient-to-r from-rose-50 to-white">
          <p className="text-xs font-semibold uppercase tracking-wider text-rose-700">Top misconception</p>
          <p className="font-display mt-1 text-2xl font-semibold text-slate-900">“{topMisconception.name}”</p>
          <div className="mt-2 flex flex-wrap items-center gap-x-6 gap-y-1 text-sm text-slate-700">
            <span><span className="text-3xl font-semibold text-rose-600">{topMisconception.students}</span> students affected</span>
            <span>Affected concept: <span className="font-semibold">{topMisconception.conceptName}</span></span>
            <Link href="/teacher/analytics" className="font-semibold text-indigo-600 hover:underline">See interventions →</Link>
          </div>
        </Card>
      )}

      <div className="mt-6 grid gap-6 lg:grid-cols-3">
        <Card className="lg:col-span-2">
          <SectionTitle hint="Class mastery by concept — red needs teaching, green is secure">Concept heatmap</SectionTitle>
          <Heatmap rows={analysis.conceptStats.map((c) => ({ label: c.name, sub: c.assessed ? `${c.struggling} struggling · ${c.mastered} mastered` : null, value: c.avgMastery }))} />
        </Card>
        <div className="space-y-6">
          <Card>
            <SectionTitle hint="Generated by aggregating learner models with transparent rules — not by an LLM">Class insights</SectionTitle>
            {insights.length ? <ul className="space-y-3">{insights.slice(0, 5).map((i) => <InsightCard key={i.id} insight={i} />)}</ul> : <p className="text-sm text-slate-500">No class-wide issues detected yet.</p>}
          </Card>
          <Card>
            <SectionTitle>Common misconceptions</SectionTitle>
            <ul className="space-y-2.5">{analysis.misconceptionStats.slice(0, 5).map((m) => <li key={m.code} className="flex items-start justify-between gap-3 text-sm"><span className="text-slate-800">{m.name}<span className="block text-xs text-slate-500">{m.conceptName}</span></span><Badge tone="rose">{m.students}</Badge></li>)}</ul>
          </Card>
        </div>
      </div>

      <div className="mt-8">
        <SectionTitle>Students</SectionTitle>
        <StudentTable students={[...analysis.students].sort((a, b) => a.overall - b.overall)} attentionIds={attentionIds} />
      </div>
      {analysis.attention.length > 0 && (
        <div className="mt-6"><Notice tone="amber" title="Why these students need attention">{analysis.attention.slice(0, 4).map((s) => `${s.name}: ${s.reasons.join(", ")}`).join(" · ")}</Notice></div>
      )}
    </>
  );
}
